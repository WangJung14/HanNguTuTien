BEGIN;

CREATE TABLE IF NOT EXISTS app_schema_migrations (
  version INTEGER PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS saved_words (
  guild_id TEXT NOT NULL, user_id TEXT NOT NULL, entry_id BIGINT NOT NULL,
  saved_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  PRIMARY KEY (guild_id, user_id, entry_id)
);
CREATE INDEX IF NOT EXISTS idx_saved_words_owner_date ON saved_words(guild_id,user_id,saved_at DESC,entry_id DESC);

CREATE TABLE IF NOT EXISTS decks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id TEXT NOT NULL, owner_id TEXT NOT NULL, name TEXT NOT NULL, name_key TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '', is_public INTEGER NOT NULL DEFAULT 0 CHECK(is_public IN(0,1)),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
  UNIQUE(guild_id,owner_id,name_key)
);
CREATE INDEX IF NOT EXISTS idx_decks_public ON decks(guild_id,is_public,id DESC);
CREATE TABLE IF NOT EXISTS deck_words (
  deck_id BIGINT NOT NULL REFERENCES decks(id) ON DELETE CASCADE, entry_id BIGINT NOT NULL,
  added_at TEXT NOT NULL, PRIMARY KEY(deck_id,entry_id)
);
CREATE INDEX IF NOT EXISTS idx_deck_words_latest ON deck_words(deck_id,added_at DESC,entry_id DESC);

CREATE TABLE IF NOT EXISTS dictation_sessions (
  id TEXT PRIMARY KEY, guild_id TEXT NOT NULL, user_id TEXT NOT NULL, deck_id BIGINT NOT NULL,
  deck_name TEXT NOT NULL, question_count INTEGER NOT NULL CHECK(question_count IN(5,10,20)),
  current_index INTEGER NOT NULL DEFAULT 0 CHECK(current_index>=0),
  status TEXT NOT NULL DEFAULT 'active' CHECK(status IN('active','completed','expired')),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL, expires_at TEXT NOT NULL,
  channel_id TEXT NOT NULL, message_id TEXT, mode TEXT NOT NULL DEFAULT 'discord' CHECK(mode IN('discord','paper'))
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_dictation_one_active_per_owner ON dictation_sessions(guild_id,user_id) WHERE status='active';
CREATE INDEX IF NOT EXISTS idx_dictation_session_expiry ON dictation_sessions(status,expires_at);
CREATE TABLE IF NOT EXISTS dictation_results (
  session_id TEXT NOT NULL REFERENCES dictation_sessions(id) ON DELETE CASCADE,
  question_index INTEGER NOT NULL CHECK(question_index>=0), entry_id BIGINT NOT NULL,
  simplified TEXT NOT NULL, traditional TEXT NOT NULL, pinyin TEXT NOT NULL, meaning_vi TEXT NOT NULL,
  answer TEXT, is_correct INTEGER CHECK(is_correct IN(0,1)), used_hint INTEGER NOT NULL DEFAULT 0 CHECK(used_hint IN(0,1)),
  replay_count INTEGER NOT NULL DEFAULT 0 CHECK(replay_count>=0), answered_at TEXT,
  PRIMARY KEY(session_id,question_index)
);
CREATE INDEX IF NOT EXISTS idx_dictation_results_entry ON dictation_results(entry_id);

CREATE TABLE IF NOT EXISTS cultivation_profiles (
  guild_id TEXT NOT NULL, user_id TEXT NOT NULL, total_xp INTEGER NOT NULL DEFAULT 0 CHECK(total_xp>=0),
  major_index INTEGER NOT NULL DEFAULT 0 CHECK(major_index>=0), role_sync_pending INTEGER NOT NULL DEFAULT 0 CHECK(role_sync_pending IN(0,1)),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL, PRIMARY KEY(guild_id,user_id)
);
CREATE TABLE IF NOT EXISTS xp_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id TEXT NOT NULL, user_id TEXT NOT NULL, amount INTEGER NOT NULL CHECK(amount>=0), source TEXT NOT NULL,
  reward_key TEXT NOT NULL UNIQUE, session_id TEXT, earned_date TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_xp_ledger_owner_date ON xp_ledger(guild_id,user_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_xp_ledger_daily ON xp_ledger(guild_id,user_id,earned_date);
CREATE TABLE IF NOT EXISTS breakthrough_attempts (
  id TEXT PRIMARY KEY, guild_id TEXT NOT NULL, user_id TEXT NOT NULL, from_major INTEGER NOT NULL,
  to_major INTEGER NOT NULL, deck_id BIGINT NOT NULL, status TEXT NOT NULL CHECK(status IN('active','passed','failed')),
  current_index INTEGER NOT NULL DEFAULT 0, correct_count INTEGER NOT NULL DEFAULT 0, questions_json TEXT NOT NULL,
  cooldown_until TEXT, message_id TEXT, created_at TEXT NOT NULL, updated_at TEXT NOT NULL, completed_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_breakthrough_one_active ON breakthrough_attempts(guild_id,user_id) WHERE status='active';
CREATE INDEX IF NOT EXISTS idx_breakthrough_history ON breakthrough_attempts(guild_id,user_id,created_at DESC);
CREATE TABLE IF NOT EXISTS guild_realm_roles (
  guild_id TEXT NOT NULL, major_index INTEGER NOT NULL, role_id TEXT NOT NULL, updated_at TEXT NOT NULL,
  PRIMARY KEY(guild_id,major_index), UNIQUE(guild_id,role_id)
);
CREATE TABLE IF NOT EXISTS xp_announcement_channels (
  guild_id TEXT PRIMARY KEY, channel_id TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS xp_admin_adjustments (
  id TEXT PRIMARY KEY, guild_id TEXT NOT NULL, user_id TEXT NOT NULL, actor_id TEXT NOT NULL,
  action TEXT NOT NULL CHECK(action IN ('reward','penalty')), amount INTEGER NOT NULL CHECK(amount >= 0),
  reason TEXT NOT NULL, previous_total_xp INTEGER NOT NULL, new_total_xp INTEGER NOT NULL,
  previous_major_index INTEGER NOT NULL, new_major_index INTEGER NOT NULL, created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS meditation_config (guild_id TEXT PRIMARY KEY,channel_id TEXT,updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS meditation_sessions (
  id TEXT PRIMARY KEY,guild_id TEXT NOT NULL,user_id TEXT NOT NULL,channel_id TEXT NOT NULL,
  status TEXT NOT NULL CHECK(status IN('active','ended')),started_at TEXT NOT NULL,next_reward_at TEXT NOT NULL,
  tick_index INTEGER NOT NULL DEFAULT 0,ended_at TEXT,updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_meditation_active ON meditation_sessions(guild_id,user_id) WHERE status='active';
CREATE TABLE IF NOT EXISTS meditation_rewards (
  session_id TEXT NOT NULL REFERENCES meditation_sessions(id),tick_index INTEGER NOT NULL,guild_id TEXT NOT NULL,
  user_id TEXT NOT NULL,activity_date TEXT NOT NULL,minutes INTEGER NOT NULL,xp_awarded INTEGER NOT NULL,created_at TEXT NOT NULL,
  PRIMARY KEY(session_id,tick_index)
);
CREATE INDEX IF NOT EXISTS idx_meditation_daily ON meditation_rewards(guild_id,user_id,activity_date);

CREATE TABLE IF NOT EXISTS daily_quest_progress (
  guild_id TEXT NOT NULL,user_id TEXT NOT NULL,activity_date TEXT NOT NULL,quest_key TEXT NOT NULL,
  progress INTEGER NOT NULL DEFAULT 0,completed_at TEXT,rewarded_at TEXT,xp_awarded INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL,PRIMARY KEY(guild_id,user_id,activity_date,quest_key)
);
CREATE TABLE IF NOT EXISTS daily_quest_entries (
  guild_id TEXT NOT NULL,user_id TEXT NOT NULL,activity_date TEXT NOT NULL,entry_id BIGINT NOT NULL,created_at TEXT NOT NULL,
  PRIMARY KEY(guild_id,user_id,activity_date,entry_id)
);
CREATE TABLE IF NOT EXISTS learning_streaks (
  guild_id TEXT NOT NULL,user_id TEXT NOT NULL,current_streak INTEGER NOT NULL DEFAULT 0,longest_streak INTEGER NOT NULL DEFAULT 0,
  last_active_date TEXT,updated_at TEXT NOT NULL,PRIMARY KEY(guild_id,user_id)
);
CREATE TABLE IF NOT EXISTS learning_activity_days (
  guild_id TEXT NOT NULL,user_id TEXT NOT NULL,activity_date TEXT NOT NULL,session_id TEXT NOT NULL UNIQUE,created_at TEXT NOT NULL,
  PRIMARY KEY(guild_id,user_id,activity_date)
);

CREATE TABLE IF NOT EXISTS mountain_matches (
  id TEXT PRIMARY KEY,guild_id TEXT NOT NULL,channel_id TEXT NOT NULL,owner_id TEXT NOT NULL,
  kind TEXT NOT NULL CHECK(kind IN('solo','multi')),deck_id BIGINT NOT NULL,deck_name TEXT NOT NULL,
  status TEXT NOT NULL CHECK(status IN('WAITING','ACTIVE','COMPLETED','CANCELLED','EXPIRED')),
  current_round INTEGER NOT NULL DEFAULT 0,message_id TEXT,round_started_at TEXT,round_deadline TEXT,
  created_at TEXT NOT NULL,updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_mountain_channel_multi ON mountain_matches(guild_id,channel_id) WHERE kind='multi' AND status IN('WAITING','ACTIVE');
CREATE TABLE IF NOT EXISTS mountain_players (
  match_id TEXT NOT NULL REFERENCES mountain_matches(id),user_id TEXT NOT NULL,display_name TEXT NOT NULL,
  score INTEGER NOT NULL DEFAULT 0,correct_count INTEGER NOT NULL DEFAULT 0,total_time_ms INTEGER NOT NULL DEFAULT 0,
  completed_rounds INTEGER NOT NULL DEFAULT 0,xp_awarded INTEGER NOT NULL DEFAULT 0,reward_date TEXT,joined_at TEXT NOT NULL,
  PRIMARY KEY(match_id,user_id)
);
CREATE INDEX IF NOT EXISTS idx_mountain_player_history ON mountain_players(user_id,joined_at DESC);
CREATE TABLE IF NOT EXISTS mountain_rounds (
  match_id TEXT NOT NULL REFERENCES mountain_matches(id),round_index INTEGER NOT NULL,question_json TEXT NOT NULL,
  opened_at TEXT,deadline TEXT,closed_at TEXT,PRIMARY KEY(match_id,round_index)
);
CREATE TABLE IF NOT EXISTS mountain_answers (
  match_id TEXT NOT NULL,round_index INTEGER NOT NULL,user_id TEXT NOT NULL,option_index INTEGER NOT NULL,
  correct INTEGER NOT NULL,elapsed_ms INTEGER NOT NULL,score INTEGER NOT NULL,answered_at TEXT NOT NULL,
  PRIMARY KEY(match_id,round_index,user_id),FOREIGN KEY(match_id,round_index) REFERENCES mountain_rounds(match_id,round_index)
);

CREATE TABLE IF NOT EXISTS pve_runs (
  id TEXT PRIMARY KEY,kind TEXT NOT NULL CHECK(kind IN('secret','boss')),guild_id TEXT NOT NULL,channel_id TEXT NOT NULL,
  owner_id TEXT NOT NULL,level TEXT NOT NULL,status TEXT NOT NULL CHECK(status IN('WAITING','ACTIVE','COMPLETED','FAILED','CANCELLED')),
  current_round INTEGER NOT NULL DEFAULT 0,correct_count INTEGER NOT NULL DEFAULT 0,score INTEGER NOT NULL DEFAULT 0,
  boss_hp INTEGER,boss_max_hp INTEGER,message_id TEXT,round_started_at TEXT,round_deadline TEXT,week_key TEXT,
  created_at TEXT NOT NULL,updated_at TEXT NOT NULL,completed_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_pve_boss_week ON pve_runs(guild_id,week_key) WHERE kind='boss';
CREATE UNIQUE INDEX IF NOT EXISTS idx_pve_boss_channel ON pve_runs(guild_id,channel_id) WHERE kind='boss' AND status IN('WAITING','ACTIVE');
CREATE TABLE IF NOT EXISTS pve_players (
  run_id TEXT NOT NULL REFERENCES pve_runs(id),user_id TEXT NOT NULL,display_name TEXT NOT NULL,
  correct_count INTEGER NOT NULL DEFAULT 0,answered_count INTEGER NOT NULL DEFAULT 0,damage INTEGER NOT NULL DEFAULT 0,
  completed_rounds INTEGER NOT NULL DEFAULT 0,xp_awarded INTEGER NOT NULL DEFAULT 0,joined_at TEXT NOT NULL,
  PRIMARY KEY(run_id,user_id)
);
CREATE INDEX IF NOT EXISTS idx_pve_history ON pve_players(user_id,joined_at DESC);
CREATE TABLE IF NOT EXISTS pve_rounds (
  run_id TEXT NOT NULL REFERENCES pve_runs(id),round_index INTEGER NOT NULL,question_json TEXT NOT NULL,
  opened_at TEXT,deadline TEXT,closed_at TEXT,PRIMARY KEY(run_id,round_index)
);
CREATE TABLE IF NOT EXISTS pve_answers (
  run_id TEXT NOT NULL,round_index INTEGER NOT NULL,user_id TEXT NOT NULL,option_index INTEGER NOT NULL,
  correct INTEGER NOT NULL,answered_at TEXT NOT NULL,PRIMARY KEY(run_id,round_index,user_id),
  FOREIGN KEY(run_id,round_index) REFERENCES pve_rounds(run_id,round_index)
);

